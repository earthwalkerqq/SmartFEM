#!/bin/bash
# Скрипт для выбора узлов в Gmsh через координаты клика
# Использует Gmsh с опцией для вывода информации о выбранных узлах

MSH_FILE="$1"
NODE_FILE="$2"
OUTPUT_FILE="$3"

if [ ! -f "$MSH_FILE" ]; then
    echo "Ошибка: Файл сетки не найден: $MSH_FILE"
    exit 1
fi

if [ ! -f "$NODE_FILE" ]; then
    echo "Ошибка: Файл узлов не найден: $NODE_FILE"
    exit 1
fi

# Создаем временный файл для выбранных узлов
TEMP_SELECTED="/tmp/gmsh_selected_nodes.txt"
echo "" > "$TEMP_SELECTED"

# Инструкция для пользователя
echo "=== Инструкция по выбору узлов в Gmsh ==="
echo "1. В Gmsh включите отображение узлов: View->Options->Mesh->Nodes"
echo "2. Кликните на узел в модели"
echo "3. В консоли Gmsh появится информация о выбранном узле"
echo "4. Введите номер узла в поле 'Номер узла' в окне выбора"
echo ""
echo "Альтернатива: Используйте список узлов слева (кликните на узел)"
echo ""

# Открываем Gmsh
gmsh "$MSH_FILE" &

# Ждем, пока пользователь выберет узлы
echo "Gmsh открыт. Выберите узлы в Gmsh и введите их номера в окне выбора."
echo "Нажмите Enter для завершения..."
read

echo "Выбор узлов завершен."

